"""The published contracts declare their sidecars, and the bytes match.

A contract whose truth lives in a machine-readable file declares it under
`artifacts:` (method 1.21), and the compiled briefing then delivers the **exact
bytes** to the consumer beside its ATLAS-CONTEXT.md. Without the declaration the
consumer's briefing carries zero bytes of the OpenAPI it is told is
generation-ready — which is what these assert against.

They run against the vault clone, so they skip where it is absent rather than
failing a checkout that has not synced.
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import re

import pytest

PROVIDES = pathlib.Path(".atlas/components/blocks-service/docs/provides")
CONTRACTS = ("blocks-service-api-contract-v0_1.md", "blocks-service-api-contract-v0_2.md")

pytestmark = pytest.mark.skipif(
    not PROVIDES.is_dir(), reason="vault clone not present; run scripts/atlas-context.sh"
)


def _declared(contract: str) -> list[tuple[str, str]]:
    frontmatter = (PROVIDES / contract).read_text().split("---")[1]
    return re.findall(r"- file: (\S+)\n\s+sha256: ([0-9a-f]{64})", frontmatter)


@pytest.mark.parametrize("contract", CONTRACTS)
def test_the_contract_declares_its_artifacts(contract: str):
    assert _declared(contract), f"{contract} declares no artifacts:"


@pytest.mark.parametrize("contract", CONTRACTS)
def test_every_declared_artifact_exists_with_the_declared_bytes(contract: str):
    """A mismatch fails the vault's validation AND the consumer's briefing.

    Deliberately, rather than degrading to a warning that invites a generator to
    guess at bytes it was told to work from.
    """
    for name, declared in _declared(contract):
        path = PROVIDES / name
        assert path.is_file(), f"{contract} declares {name}, which does not exist"
        actual = hashlib.sha256(path.read_bytes()).hexdigest()
        assert actual == declared, f"{name}: declared {declared[:12]}…, actual {actual[:12]}…"


def test_every_shipped_sidecar_is_declared_by_some_contract():
    """The direction that catches an artefact added and quietly not published."""
    declared = {name for c in CONTRACTS for name, _ in _declared(c)}
    shipped = {p.name for p in PROVIDES.glob("*.json")}
    assert not shipped - declared, f"undeclared sidecars: {sorted(shipped - declared)}"


def test_the_0_2_declaration_covers_every_current_event_schema():
    """An event type registered in code but not published is invisible to a consumer."""
    import sys

    sys.path.insert(0, "src")
    from blocks_service import events

    declared = {name for name, _ in _declared("blocks-service-api-contract-v0_2.md")}
    for event_type, version in events.EVENT_VERSIONS.items():
        expected = f"{event_type.replace('.', '-')}-v{version.replace('.', '_')}.schema.json"
        assert expected in declared, f"{event_type} {version} is not declared"


def test_the_declared_openapi_is_the_one_the_service_generates():
    """The published bytes must be the generated bytes, not a stale export."""
    import sys

    sys.path.insert(0, "src")
    from blocks_service.app import create_app
    from blocks_service.config import Settings

    live = create_app(
        Settings(db_app_password="unused", dev_token_secret="unused-for-schema-only")
    ).openapi()
    published = json.loads((PROVIDES / "blocks-service-api-openapi-v0_2.json").read_text())
    assert published == live, "published OpenAPI is stale; re-run tools/export_contract.py"
