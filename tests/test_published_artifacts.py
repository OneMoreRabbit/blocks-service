"""The published contracts declare their sidecars, and the bytes match.

A contract whose truth lives in a machine-readable file declares it under
`artifacts:` (method 1.21), and the compiled briefing then delivers the **exact
bytes** to the consumer beside its ATLAS-CONTEXT.md. Without the declaration the
consumer's briefing carries zero bytes of the OpenAPI it is told is
generation-ready — which is what these assert against.

They run against the vault clone, so they skip where it is absent rather than
failing a checkout that has not synced.
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import re

import pytest

PROVIDES = pathlib.Path(".atlas/components/blocks-service/docs/provides")
CONTRACTS = (
    "blocks-service-api-contract-v0_1.md",
    "blocks-service-api-contract-v0_2.md",
    "blocks-service-api-contract-v0_3.md",
    "blocks-service-api-contract-v0_4.md",
    "blocks-service-api-contract-v0_5.md",
)

#: The version the service currently generates. Older published contracts are
#: immutable: their artefacts are the bytes consumers were handed, and a stale
#: comparison against the live app would be asserting that history should change.
CURRENT = "0_5"

pytestmark = pytest.mark.skipif(
    not PROVIDES.is_dir(), reason="vault clone not present; run scripts/atlas-context.sh"
)


#: Superseded contracts and the sidecars only they declare live under
#: provides/archive/. Archiving is a filing decision, not a withdrawal: the bytes
#: consumers were handed are unchanged and every assertion below still applies to
#: them, so resolution follows the file rather than assuming the live directory.
ARCHIVE = PROVIDES / "archive"


def _resolve(name: str) -> pathlib.Path:
    live = PROVIDES / name
    return live if live.exists() else ARCHIVE / name


def _declared(contract: str) -> list[tuple[str, str]]:
    frontmatter = _resolve(contract).read_text().split("---")[1]
    return re.findall(r"- file: (\S+)\n\s+sha256: ([0-9a-f]{64})", frontmatter)


@pytest.mark.parametrize("contract", CONTRACTS)
def test_the_contract_declares_its_artifacts(contract: str):
    assert _declared(contract), f"{contract} declares no artifacts:"


@pytest.mark.parametrize("contract", CONTRACTS)
def test_every_declared_artifact_exists_with_the_declared_bytes(contract: str):
    """A mismatch fails the vault's validation AND the consumer's briefing.

    Deliberately, rather than degrading to a warning that invites a generator to
    guess at bytes it was told to work from.
    """
    for name, declared in _declared(contract):
        path = _resolve(name)
        assert path.is_file(), f"{contract} declares {name}, which does not exist"
        actual = hashlib.sha256(path.read_bytes()).hexdigest()
        assert actual == declared, f"{name}: declared {declared[:12]}…, actual {actual[:12]}…"


def test_every_shipped_sidecar_is_declared_by_some_contract():
    """The direction that catches an artefact added and quietly not published."""
    declared = {name for c in CONTRACTS for name, _ in _declared(c)}
    shipped = {p.name for p in PROVIDES.glob("*.json")} | {
        p.name for p in ARCHIVE.glob("*.json")
    }
    assert not shipped - declared, f"undeclared sidecars: {sorted(shipped - declared)}"


def test_the_current_declaration_covers_every_event_schema():
    """An event type registered in code but not published is invisible to a consumer.

    Checked against the CURRENT contract. A 0.3 consumer's change feed can still
    carry legacy `session.*` events during the declared 0.2 compatibility window,
    so 0.3 declares those schemas too — a client cannot validate what it receives
    otherwise.
    """
    import sys

    sys.path.insert(0, "src")
    from blocks_service import events

    declared = {name for name, _ in _declared(f"blocks-service-api-contract-v{CURRENT}.md")}
    for event_type, version in events.EVENT_VERSIONS.items():
        expected = f"{event_type.replace('.', '-')}-v{version.replace('.', '_')}.schema.json"
        assert expected in declared, f"{event_type} {version} is not declared"


def test_the_current_openapi_is_the_one_the_service_generates():
    """The published bytes must be the generated bytes, not a stale export.

    Only the CURRENT version is compared. 0.1 and 0.2 are immutable: they describe
    what was accepted, and the service has moved past both.
    """
    import subprocess
    import sys
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(
            [sys.executable, "tools/export_contract.py", "--out", tmp],
            check=True, capture_output=True,
        )
        regenerated = json.loads(
            (pathlib.Path(tmp) / f"blocks-service-api-openapi-v{CURRENT}.json").read_text()
        )
    published = json.loads(
        (PROVIDES / f"blocks-service-api-openapi-v{CURRENT}.json").read_text()
    )
    assert published == regenerated, "published OpenAPI is stale; re-run tools/export_contract.py"


def test_the_superseded_contracts_are_untouched_by_the_current_service():
    """0.1 and 0.2 artefacts must not move when the service changes.

    Their hashes are declared and consumers were handed those exact bytes. This is
    the assertion that catches a regeneration accidentally overwriting them.
    """
    for older in ("0_1", "0_2", "0_3", "0_4"):
        for name, declared in _declared(f"blocks-service-api-contract-v{older}.md"):
            actual = hashlib.sha256(_resolve(name).read_bytes()).hexdigest()
            assert actual == declared, f"{name} moved under published {older}"
